"""26.2 codecs: official Java StreamCodec fixtures + lifecycle and safety tests."""
import asyncio
import unittest
import uuid
from mcbot import modern_packets as p
from mcbot.modern_client import ModernMinecraftClient
from mcbot.buffer import BufferReader as R, BufferWriter as W
from mcbot.registry import BlockRegistry
from mcbot.types import Vec3, BlockPos
from mcbot.nbt import write_nbt


def unnamed(value):
    raw = write_nbt(value)
    return raw[:1] + raw[3:]


class Client(ModernMinecraftClient):
    def __init__(self):
        super().__init__('localhost', registry=BlockRegistry())
        self.sent = []
    def _write_frame(self, pid, payload=b''):
        self.sent.append((pid,payload))


class ModernProtocolTests(unittest.TestCase):
    def test_official_ids(self):
        self.assertEqual(p.PROTOCOL_VERSION,776)
        self.assertEqual(p.PLAY_CLIENTBOUND['login'],49)
        self.assertEqual(p.PLAY_SERVERBOUND['attack'],1)
        self.assertEqual(p.CONFIGURATION_SERVERBOUND['finish_configuration'],3)

    def test_login_uuid_not_optional(self):
        identity=uuid.UUID(int=123)
        r=R(p.login_start('Bot',identity))
        self.assertEqual(r.read_string(),'Bot')
        self.assertEqual(r.read_uuid(),identity)
        self.assertEqual(r.remaining,0)

    def test_unnamed_nbt(self):
        r=R(unnamed({'text':'你好','extra':[{'text':'世界'}]})+b'!')
        self.assertEqual(p.component(r),'你好世界')
        self.assertEqual(r.read_rest(),b'!')

    def test_official_java_position_fixture(self):
        # Generated by ClientboundPlayerPositionPacket.STREAM_CODEC in official
        # server-26.2.jar; generator research-26.2/client-work/Fixtures.java.
        raw=bytes.fromhex('ac023ff40000000000004051800000000000c0160000000000003fb999999999999a3fc999999999999a3fd333333333333342b400004140000000000041')
        c=Client(); c.position=Vec3(10,20,30); c.velocity=Vec3(1,2,3)
        r=R(raw); c._position(r)
        self.assertEqual(r.remaining,0)
        self.assertEqual(c.position,Vec3(11.25,70,-5.5))
        self.assertAlmostEqual(c.velocity.y,2.2)
        self.assertEqual(c.sent[0],(0,b'\xac\x02'))
        self.assertEqual(c.sent[-1],(p.PLAY_SERVERBOUND['player_loaded'],b''))

    def test_official_java_lp_vector_fixture(self):
        value=p.lp_vec3(R(bytes.fromhex('f9fffffcbffe')))
        self.assertAlmostEqual(value.x,.5,delta=.0001)
        self.assertAlmostEqual(value.y,-.25,delta=.0001)
        self.assertAlmostEqual(value.z,1.,delta=.0001)

    def test_official_java_use_item_attack_fixture(self):
        self.assertEqual(p.use_item(0,12,90,12).hex(),'000c42b4000041400000')
        c=Client(); c.attack(300)
        self.assertEqual(c.sent[-1],(1,bytes.fromhex('ac02')))

    def test_config_registry_and_negotiation(self):
        c=Client(); c.state='configuration'
        body=W().write_string('minecraft:dimension_type').write_varint(1).write_string('minecraft:overworld').write_bool(True).write(unnamed({'min_y':-64,'height':384})).to_bytes()
        c._configuration(7,R(body))
        self.assertEqual(c.registries['minecraft:dimension_type'][0][1]['min_y'],-64)
        c._configuration(14,R(W().write_varint(1).write_string('minecraft').write_string('core').write_string('26.2').to_bytes()))
        self.assertEqual(c.sent[-1],(7,b'\x00'))
        c._configuration(4,R(b'12345678')); self.assertEqual(c.sent[-1],(4,b'12345678'))
        c._configuration(5,R(b'1234')); self.assertEqual(c.sent[-1],(5,b'1234'))
        c._configuration(0,R(W().write_string('x:y').to_bytes()))
        self.assertEqual(c.sent[-1],(1,W().write_string('x:y').write_bool(False).to_bytes()))
        c._configuration(3,R(b'')); self.assertEqual(c.state,'play')

    def test_resource_pack_decline(self):
        c=Client(); identity=uuid.UUID(int=1)
        c._resource_pack(R(W().write_uuid(identity).write_string('https://example.invalid').write_string('').write_bool(True).write_bool(False).to_bytes()),p.CONFIGURATION_SERVERBOUND)
        self.assertEqual(c.sent[-1],(6,identity.bytes+b'\x01'))

    def test_slot_components_and_unknown_fail_closed(self):
        item=p.decode_slot(R(bytes([2,5,1,0,3,12])))
        self.assertEqual((item.count,item.item_id,item.nbt['damage']),(2,5,12))
        with self.assertRaises(p.UnsupportedComponent): p.decode_slot(R(bytes([1,5,1,0,127,0])))
        c=Client(); c.inventory={7:'unchanged'}
        payload=bytes([0,0,2,0,1,5,1,0,127,0,0])
        c._inventory('container_set_content',R(payload))
        self.assertEqual(c.inventory,{7:'unchanged'})
        self.assertEqual(c.inventory_errors,1)

    def test_player_info_all_actions(self):
        c=Client(); identity=uuid.UUID(int=1)
        raw=W().write_u8(255).write_varint(1).write_uuid(identity).write_string('Alice').write_varint(0).write_bool(False).write_varint(1).write_bool(True).write_varint(25).write_bool(True).write(unnamed({'text':'Display'})).write_varint(7).write_bool(True).to_bytes()
        r=R(raw); c._player_info(r)
        self.assertEqual(r.remaining,0)
        self.assertEqual(c.players[identity].name,'Alice')
        self.assertEqual(c.players[identity].latency,25)

    def test_chat_extra_checksum_and_command_unsigned(self):
        r=R(p.chat_message('x',123))
        self.assertEqual(r.read_string(),'x'); self.assertEqual(r.read_i64(),123)
        r.read_i64(); self.assertFalse(r.read_bool()); self.assertEqual(r.read_varint(),0)
        self.assertEqual(r.read_rest(),b'\x00'*4)
        c=Client(); c.send_command('/help')
        self.assertEqual(c.sent[-1],(7,b'\x04help'))

    def test_new_world_clock_not_legacy_double_long(self):
        c=Client(); c.registries['minecraft:world_clock']=[('minecraft:overworld',{})]
        r=R(W().write_i64(100).write_varint(1).write_varint(0).write_varlong(6000).write_f32(.5).write_f32(1).to_bytes())
        c._dispatch(p.PLAY_CLIENTBOUND['set_time'],r)
        self.assertEqual(r.remaining,0)
        self.assertEqual(c.world.day_time,6000)

    def test_chunk_batch_and_move_flags(self):
        c=Client(); c._dispatch(11,R(b'\x01'))
        self.assertEqual(c.sent[-1],(11,W().write_f32(8).to_bytes()))
        c.set_sneaking(True); c.set_sprinting(True)
        self.assertEqual(c.sent[-1],(43,b'\x60'))
        c.send_position(Vec3(1,2,3),10,20,True)
        self.assertEqual(len(c.sent[-1][1]),33)


class LoginLifecycleTests(unittest.IsolatedAsyncioTestCase):
    async def test_login_ack_configuration_complete_sequence(self):
        c=Client()
        class Writer:
            async def drain(self): pass
        c._writer=Writer()
        identity=uuid.UUID(int=456)
        frames=iter([
            (2,R(W().write_uuid(identity).write_string('Bot').write_varint(0).to_bytes())),
            (14,R(b'\x00')),
            (4,R(b'12345678')),
            (3,R(b'')),
        ])
        async def read(): return next(frames)
        c._read_frame=read
        await c._login()
        self.assertEqual(c.state,'play')
        self.assertEqual(c.session.uuid,identity)
        self.assertEqual([pid for pid,_ in c.sent],[0,0,3,0,7,4,3])
        r=R(c.sent[0][1]); self.assertEqual(r.read_varint(),776)
        r=R(c.sent[1][1]); self.assertEqual(r.read_string(),'MaiBot'); r.read_uuid(); self.assertEqual(r.remaining,0)

    async def test_threshold_zero_compresses(self):
        import zlib
        c=ModernMinecraftClient('localhost',registry=BlockRegistry())
        class Writer:
            def write(self,data): self.data=data
        writer=Writer(); c._writer=writer; c._compression=0
        c._write_frame(1,b'abc')
        r=R(writer.data); length=r.read_varint(); inner=R(r.read(length))
        self.assertEqual(inner.read_varint(),4)
        self.assertEqual(zlib.decompress(inner.read_rest()),b'\x01abc')


if __name__ == '__main__': unittest.main()
